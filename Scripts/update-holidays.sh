#!/bin/bash
# Downloads the holiday data compiled into the app and regenerates Sources/CalendarCore/BundledHolidays.swift.
# Run it when China publishes next year's schedule (around November) or Japan updates its list.
#   Scripts/update-holidays.sh            China: last year … next year
#   Scripts/update-holidays.sh 2025 2028  China: those years (missing ones are skipped)
# The app also downloads newer files by itself (HolidayUpdater), so this only sets the offline baseline.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p Data/raw
THIS=$(date +%Y)
FROM="${1:-$((THIS - 1))}"
TO="${2:-$((THIS + 1))}"
for y in $(seq "$FROM" "$TO"); do
    if curl -sf "https://cdn.jsdelivr.net/gh/NateScarlet/holiday-cn@master/$y.json" -o "Data/raw/cn-$y.json.tmp" \
       || curl -sf "https://raw.githubusercontent.com/NateScarlet/holiday-cn/master/$y.json" -o "Data/raw/cn-$y.json.tmp"; then
        mv "Data/raw/cn-$y.json.tmp" "Data/raw/cn-$y.json"; echo "cn $y: ok"
    else
        rm -f "Data/raw/cn-$y.json.tmp"; echo "cn $y: not published"
    fi
done
curl -sf "https://www8.cao.go.jp/chosei/shukujitsu/syukujitsu.csv" | iconv -f SHIFT_JIS -t UTF-8 > Data/raw/jp-syukujitsu.csv.tmp \
    && mv Data/raw/jp-syukujitsu.csv.tmp Data/raw/jp-syukujitsu.csv && echo "jp: ok"

python3 -I - <<'PY'
import glob, json, re
out = ["// Generated by Scripts/update-holidays.sh from Data/raw/. Do not edit by hand.",
       "// China: github.com/NateScarlet/holiday-cn (MIT). Japan: Cabinet Office syukujitsu.csv (2020 onward).",
       "enum BundledHolidays {", "    static let cn: [Int: String] = ["]
for path in sorted(glob.glob("Data/raw/cn-*.json")):
    data = json.load(open(path, encoding="utf-8"))
    slim = {"year": data["year"], "days": [{"name": d["name"], "date": d["date"], "isOffDay": d["isOffDay"]} for d in data["days"]]}
    out.append(f'        {data["year"]}: #"""')
    out.append("        " + json.dumps(slim, ensure_ascii=False))
    out.append('        """#,')
out.append("    ]")
rows = [l.strip() for l in open("Data/raw/jp-syukujitsu.csv", encoding="utf-8") if re.match(r"^20[2-9]\d/", l)]
out.append('    static let jpCSV = #"""')
out += ["    " + r for r in rows]
out.append('    """#')
out.append("}")
open("Sources/CalendarCore/BundledHolidays.swift", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote Sources/CalendarCore/BundledHolidays.swift")
PY
